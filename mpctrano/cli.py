"""Command line interface: ``mpctrano --help``."""

from __future__ import annotations

from pathlib import Path
from typing import Annotated

import pandas as pd
import typer

from mpctrano.calibration import CalibrationSettings
from mpctrano.data import MonitoringData
from mpctrano.model import CLOSED_LOOP_LIBRARY, MPC_LIBRARY, BuildingModel
from mpctrano.project import Project
from mpctrano.scenarios import scenario_catalogue

app = typer.Typer(
    help="Calibration, state estimation and economic MPC of the FastSmoothBuildings models generated by Trano.",
    no_args_is_help=True,
)
CHECK = "✔"

BuildingArgument = Annotated[Path, typer.Argument(help="Trano building description (.yaml)")]
WeatherOption = Annotated[
    Path | None, typer.Option(help="TMY3 .mos weather file (default: the file of the model, next to the YAML)")
]


def _project(building: Path, weather: Path | None, calibrated: Path | None = None) -> Project:
    project = Project.from_yaml(building, weather=weather)
    if calibrated is not None:
        project.load_calibrated(calibrated)
    return project


@app.command()
def generate(
    building: BuildingArgument,
    output: Annotated[Path | None, typer.Option(help="Output directory (default: next to the YAML)")] = None,
    closed_loop: Annotated[bool, typer.Option(help="Also write the closed-loop BuildingModel (rule-based)")] = False,
) -> None:
    """Generate the FastSmoothBuildingsMPC package (the controls of the systems as inputs) with Trano."""
    directory = output or building.parent
    for library, suffix in ((MPC_LIBRARY, ""), (CLOSED_LOOP_LIBRARY, ".closed_loop")):
        if library == CLOSED_LOOP_LIBRARY and not closed_loop:
            continue
        model = BuildingModel.from_yaml(building, library=library)
        path = model.write(directory, f"{building.stem}{suffix}")
        size = f"{model.n_states} states, {model.n_controls} controls, {len(model.meters)} meters"
        typer.echo(f"{CHECK} {path} written ({library}: {size})")


@app.command("synthetic-data")
def synthetic_data(
    building: BuildingArgument,
    output: Annotated[Path, typer.Option(help="CSV file to write")] = Path("monitoring.csv"),
    days: Annotated[float, typer.Option(help="Length of the data")] = 7,
    start: Annotated[str, typer.Option(help="First timestamp")] = "2023-01-02",
    seed: Annotated[int, typer.Option(help="Seed of the perturbed 'true' building")] = 0,
    weather: WeatherOption = None,
) -> None:
    """Record monitoring data on a perturbed copy of the model (to try the package without a building)."""
    project = _project(building, weather)
    synthetic = project.synthetic_data(days=days, start=start, building=project.true_building(seed=seed))
    synthetic.data.to_csv(output)
    typer.echo(f"{CHECK} {len(synthetic.data)} samples written to {output}")


@app.command()
def calibrate(
    building: BuildingArgument,
    data: Annotated[Path, typer.Argument(help="Monitoring data CSV (time, <zone>.TAir, the controls, the meters)")],
    output: Annotated[
        Path | None, typer.Option(help="Directory of the calibration (default: next to the YAML)")
    ] = None,
    validation_fraction: Annotated[float, typer.Option(min=0, max=0.9)] = 0.25,
    temperature_unit: Annotated[str, typer.Option(help="Unit of the temperatures in the CSV: K or C")] = "K",
    regularization: Annotated[float, typer.Option(min=0)] = 1.0,
    weather: WeatherOption = None,
) -> None:
    """Calibrate the parameter groups on monitoring data and write <building>.calibration.json."""
    project = _project(building, weather)
    monitoring = MonitoringData.from_csv(data, temperature_unit=temperature_unit)
    settings = CalibrationSettings(regularization=regularization)
    result = project.calibrate(monitoring, settings=settings, validation_fraction=validation_fraction or None)
    written = project.save(output or building.parent, building.stem)
    typer.echo(pd.Series(result.factors, name="factor").round(3).to_string())
    typer.echo(result.metrics().round(3).to_string())
    typer.echo(f"{CHECK} calibration written to {written['calibration']}")


@app.command()
def run(
    building: BuildingArgument,
    scenario: Annotated[str, typer.Option(help="Scenario name, see `mpctrano scenarios`")] = "time_of_use",
    calibrated: Annotated[Path | None, typer.Option(help="Calibration JSON to control with")] = None,
    output: Annotated[Path | None, typer.Option(help="CSV file of the closed-loop trajectories")] = None,
    days: Annotated[float, typer.Option()] = 2,
    start: Annotated[str, typer.Option()] = "2023-01-16",
    horizon: Annotated[int, typer.Option(help="Prediction horizon [h]")] = 24,
    seed: Annotated[int | None, typer.Option(help="Seed of the perturbed plant (default: the model itself)")] = None,
    rule_based: Annotated[bool, typer.Option(help="Also run the controllers of the YAML on the same building")] = False,
    weather: WeatherOption = None,
) -> None:
    """Closed-loop MPC run of a scenario (state estimation + MPC against a simulated building)."""
    catalogue = scenario_catalogue(start=start, days=days, horizon=horizon)
    if scenario not in catalogue:
        raise typer.BadParameter(f"Unknown scenario {scenario!r}, choose among {sorted(catalogue)}.")
    project = _project(building, weather, calibrated)
    plant = project.true_building(seed=seed) if seed is not None else project.control_model
    results = [project.run(catalogue[scenario], plant=plant)]
    if rule_based:
        reference = project.true_closed_loop(seed=seed) if seed is not None else None
        results.append(project.run_rule_based(catalogue[scenario], building=reference))
    typer.echo(pd.DataFrame({result.name: result.summary() for result in results}).round(3).to_string())
    if output is not None:
        results[0].frame.to_csv(output)
        typer.echo(f"{CHECK} trajectories written to {output}")


@app.command()
def scenarios() -> None:
    """List the scenarios shipped with the package."""
    for name, scenario in scenario_catalogue().items():
        typer.echo(f"{name:20s} {scenario.description}")


if __name__ == "__main__":
    app()
