"""Calibrate a multi-zone heat pump house, declared in a Trano YAML, on two weeks of monitoring data.

The building is ``scripts/multizone_heat_pump.yaml`` by default: six rooms, radiators with P-controlled valves, an
air-to-water heat pump with a buffer; three fields are declared as calibration parameters in the YAML
(``{value, parameter: true, min, max}``). The monitoring data a real building would give (the air temperature of
every room and the electricity meter of the heat pump, hourly, noisy) is generated by Trano itself: the same YAML
with other values of the declared fields (``--truth``), run by its own controllers over the Uccle weather. The
calibration then recovers these values from the data with the model at the YAML values::

    uv run python scripts/calibrate_multizone.py                      # the house, 14 days from 9 January
    uv run python scripts/calibrate_multizone.py --days 7 --start 2023-02-06
    uv run python scripts/calibrate_multizone.py --yaml my_house.yaml --weather weather/ --truth '{...}'

Outputs, in ``--output`` (``scripts/output`` by default): ``monitoring.csv`` (the data), ``calibration.json`` (the
result), ``<yaml>-calibrated.yaml`` (the YAML with the calibrated values, as Trano reads it) and ``fit.html``
(measured against simulated, before and after). Runtime on four cores: 3 to 5 minutes to generate the five models
(the building, the truth, one per declared field for the sensitivities), 5 to 15 minutes for the fit.
"""

from __future__ import annotations

import json
import os
import time
from pathlib import Path
from typing import Annotated

import numpy as np
import pandas as pd
import typer

from mpctrano import CalibrationSettings, CalibrationSpec, Calibrator, generate_closed_loop_data, spin_up
from mpctrano.calibration import simulate_fit
from mpctrano.data import MonitoringData
from mpctrano.model import CLOSED_LOOP_LIBRARY
from mpctrano.plot import plot_fit

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
YAML = HERE / "multizone_heat_pump.yaml"
WEATHER = ROOT / "tests" / "models"
"""The directory holding the Uccle TMYx weather file (``BEL_VLG_Uccle.064470_TMYx.2007-2021.mos``)."""
TRUTH = {
    "material[MINERAL_WOOL:001].thermal_conductivity": 0.055,  # the insulation is worse than its data sheet
    "spaces[LIVINGROOM:001].parameters.ach": 1.0,  # the living room is leakier than assumed
    "spaces[BEDROOM_2:001].parameters.ach": 0.8,
}
"""The values of the declared fields in the true building; the YAML holds the assumed ones."""
app = typer.Typer(add_completion=False, help=__doc__)


def hourly_power(meter: pd.Series, name: str) -> pd.Series:
    """The average power [kW] over each hour, from the readings of an energy meter [kWh]."""
    hours = meter.index.to_series().diff().dt.total_seconds() / 3600.0
    return pd.Series(meter.diff() / hours, name=name)


@app.command()
def main(
    yaml: Annotated[Path, typer.Option(help="The annotated Trano YAML of the building.")] = YAML,
    weather: Annotated[Path, typer.Option(help="Directory with the weather file the YAML refers to.")] = WEATHER,
    start: Annotated[str, typer.Option(help="First day of the monitoring data.")] = "2023-01-09",
    days: Annotated[float, typer.Option(help="Length of the monitoring data [days].")] = 14.0,
    training_days: Annotated[float, typer.Option(help="Days used by the fit; the rest validates it.")] = 10.0,
    truth: Annotated[str | None, typer.Option(help="JSON of the true values of the declared fields.")] = None,
    temperature_noise: Annotated[float, typer.Option(help="Noise of the air temperature sensors [K].")] = 0.1,
    meter_noise: Annotated[float, typer.Option(help="Noise of the electricity meter readings [kWh].")] = 0.02,
    max_iterations: Annotated[int, typer.Option(help="IPOPT iterations at most.")] = 40,
    workers: Annotated[int, typer.Option(help="Processes for the gradient (2 x fields simulations).")] = os.cpu_count()
    or 1,
    output: Annotated[Path, typer.Option(help="Where the data, the result and the figure go.")] = HERE / "output",
    seed: int = 0,
) -> None:
    """Generate two weeks of monitoring data of the true building and calibrate the YAML on them."""
    output.mkdir(parents=True, exist_ok=True)
    true_values = TRUTH if truth is None else {str(k): float(v) for k, v in json.loads(truth).items()}
    spec = CalibrationSpec.from_yaml(yaml, base_dir=weather)
    print(f"{yaml.name}: {len(spec.parameters)} declared fields")
    for parameter in spec.parameters:
        print(f"  {parameter.path}: {parameter.value:g} in [{parameter.lower:g}, {parameter.upper:g}]"
              f" (true {true_values.get(parameter.path, parameter.value):g})")  # fmt: skip

    started = time.perf_counter()
    model = spec.model(CLOSED_LOOP_LIBRARY)
    building = spec.model(CLOSED_LOOP_LIBRARY, true_values)
    print(f"models generated in {time.perf_counter() - started:.0f} s: {model.n_states} states, "
          f"zones {model.zone_names}, meters {list(model.meters)}")  # fmt: skip

    # the true building, operated by its own controllers, after three days of spin-up: its monitoring system logs
    # the air temperature of every room and the electricity meter of the heat pump
    x0 = spin_up(building, building, start, days=3.0)
    recorded = generate_closed_loop_data(
        building, start, days, measurement_std=temperature_noise, meter_std=meter_noise, seed=seed, x0=x0
    )
    frame = recorded.data.frame.copy()
    for meter in model.meters:  # the heating power of the heat pump: the electricity it draws, hour by hour
        frame[f"{meter}_power_kW"] = hourly_power(frame[meter], f"{meter}_power_kW")
    data = MonitoringData(frame.drop(columns=[c for c in frame.columns if c.endswith("_kW")]))
    frame.to_csv(output / "monitoring.csv", index_label="time")
    print(f"monitoring data: {len(frame) - 1} hours from {frame.index[0]} -> {output / 'monitoring.csv'}")
    print(frame[[*model.comfort_states, *[c for c in frame.columns if c.endswith("_kW")]]].describe().round(2).T)

    steps = round(training_days * 24)
    training, validation = data.frame.iloc[: steps + 1], data.frame.iloc[steps:]

    started = time.perf_counter()
    groups = spec.groups(model, CLOSED_LOOP_LIBRARY)
    print(f"sensitivities measured in {time.perf_counter() - started:.0f} s:")
    for group in groups:
        print(f"  {group.name}: {len(group.exponents)} parameters of the model")

    started = time.perf_counter()
    calibrator = Calibrator(model, CalibrationSettings(groups=groups, max_iterations=max_iterations, workers=workers))
    calibrated, result = calibrator.fit(training, validation)
    print(f"calibration ({result.method}): {result.status} in {result.iterations} iterations, "
          f"{time.perf_counter() - started:.0f} s")  # fmt: skip

    table = pd.DataFrame({"assumed (YAML)": spec.nominal, "calibrated": result.factors})
    table["true"] = pd.Series(true_values).reindex(table.index).fillna(table["assumed (YAML)"])
    table["error %"] = 100 * (table["calibrated"] - table["true"]) / table["true"]
    print(table.round(4).to_string())
    print(result.metrics().round(3).to_string())

    (output / "calibration.json").write_text(result.model_dump_json(indent=1))
    calibrated_yaml = spec.write(result.factors, directory=output).rename(output / f"{yaml.stem}-calibrated.yaml")
    figure = plot_fit(
        pd.concat(
            [
                simulate_fit(model, training).add_suffix(" (before)"),
                simulate_fit(calibrated, training, np.asarray(result.initial_state)).add_suffix(" (after)"),
            ],
            axis=1,
        ),
        f"{yaml.stem}: training days, measured (dotted) against simulated before and after the calibration",
    )
    figure.write_html(output / "fit.html")
    print(f"written: {output / 'calibration.json'}, {calibrated_yaml}, {output / 'fit.html'}")


if __name__ == "__main__":
    app()
