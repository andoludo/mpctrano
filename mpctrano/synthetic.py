"""Synthetic buildings and monitoring data, for tests, tutorials and controller studies.

A *true* building is obtained by perturbing the parameters of the Trano model
(:func:`perturb`); monitoring data is generated by driving it with a randomised thermostat
(:func:`generate_monitoring_data`), which excites the dynamics enough for calibration.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd
from pydantic import BaseModel, ConfigDict, Field

from mpctrano.data import MonitoringData
from mpctrano.forecast import Forecaster, forecast_index
from mpctrano.model import KELVIN, RCModel

FRACTION_UNIT = "1"


def perturb(
    model: RCModel, relative_std: float = 0.3, seed: int | None = 0, parameters: list[str] | None = None
) -> RCModel:
    """Log-normal multiplicative perturbation of the envelope parameters.

    Fractions, ``TGro`` and the parameters of the energy systems (COP, capacities, limits) are left
    untouched unless ``parameters`` selects them explicitly.
    """
    generator = np.random.default_rng(seed)
    names = model.select_parameters(parameters) if parameters else model.parameter_names
    values = model.parameters.copy()
    for index, (name, specification) in enumerate(zip(model.parameter_names, model.interface.parameters, strict=True)):
        if name not in names or name == "TGro" or specification.unit == FRACTION_UNIT:
            continue
        if parameters is None and specification.system is not None:
            continue
        values[index] *= float(np.exp(generator.normal(0, relative_std)))
    return model.with_parameters(values)


class ExcitationSettings(BaseModel):
    """Randomised thermostat used to generate informative monitoring data."""

    model_config = ConfigDict(frozen=True)

    setpoint_low: float = Field(17.0, description="[degC]")
    setpoint_high: float = Field(23.0, description="[degC]")
    hold_hours: tuple[float, float] = Field((3.0, 12.0), description="Range of the duration of a setpoint")
    gain: float = Field(1500.0, gt=0, description="Proportional gain of the thermostat [W/K]")
    seed: int | None = 0


@dataclass(frozen=True)
class SyntheticData:
    data: MonitoringData
    """What a monitoring system would record."""
    states: pd.DataFrame
    """The true states (not available in practice)."""
    setpoints: pd.DataFrame


def generate_monitoring_data(
    model: RCModel,
    forecaster: Forecaster,
    start: pd.Timestamp | str,
    days: float,
    time_step: float = 3600.0,
    excitation: ExcitationSettings | None = None,
    measurement_std: float = 0.05,
    x0: np.ndarray | None = None,
) -> SyntheticData:
    """Simulate ``model`` (the true building) with a randomised thermostat and record the data."""
    excitation = excitation or ExcitationSettings()
    generator = np.random.default_rng(excitation.seed)
    steps = round(days * 86400 / time_step)
    index = forecast_index(pd.Timestamp(start), steps + 1, time_step)
    disturbances = forecaster.realisation(pd.Timestamp(start), steps, time_step)
    dynamics = model.discrete(time_step)
    max_power = model.max_heating_power
    n_zones = model.n_zones
    heating = model.zone_heating_indices

    setpoints = np.zeros((n_zones, steps))
    for zone in range(n_zones):
        k = 0
        while k < steps:
            hold = round(generator.uniform(*excitation.hold_hours) * 3600 / time_step) or 1
            setpoints[zone, k : k + hold] = (
                generator.uniform(excitation.setpoint_low, excitation.setpoint_high) + KELVIN
            )
            k += hold

    x = model.initial_state.copy() if x0 is None else np.asarray(x0, dtype=float).copy()
    states = np.zeros((model.n_states, steps + 1))
    controls = np.zeros((model.n_controls, steps))
    states[:, 0] = x
    for k in range(steps):
        temperatures = x[model.comfort_indices]
        controls[heating, k] = np.clip(excitation.gain * (setpoints[:, k] - temperatures), 0, max_power)
        x = np.asarray(
            dynamics(x, controls[:, k], disturbances.iloc[k].to_numpy(dtype=float), model.parameters), dtype=float
        ).reshape(-1)
        states[:, k + 1] = x

    frame = pd.DataFrame(index=index)
    frame.index.name = "time"
    noise = generator.normal(0, measurement_std, (n_zones, steps + 1))
    for position, state_index in enumerate(model.comfort_indices):
        frame[model.state_names[state_index]] = states[state_index] + noise[position]
    for position, name in enumerate(model.control_names):
        frame[name] = np.append(controls[position], controls[position, -1])
    for name in model.disturbance_names:
        values = disturbances[name].to_numpy(dtype=float)
        frame[name] = np.append(values, values[-1])
    setpoint_frame = pd.DataFrame(
        np.hstack([setpoints, setpoints[:, -1:]]).T,
        index=index,
        columns=[f"{zone}_setpoint" for zone in model.zone_names],
    )
    return SyntheticData(
        data=MonitoringData(frame),
        states=pd.DataFrame(states.T, index=index, columns=model.state_names),
        setpoints=setpoint_frame,
    )
