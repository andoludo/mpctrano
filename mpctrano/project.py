"""High-level facade: from a Trano building to a calibrated model and closed-loop MPC runs."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd
from trano.mpc import RCModelType

from mpctrano.calibration import CalibrationResult, CalibrationSettings, Calibrator
from mpctrano.data import MonitoringData
from mpctrano.forecast import ForecastNoise, Forecaster, OccupancySchedule, WeatherForecaster
from mpctrano.model import RCModel
from mpctrano.mpc import ModelPredictiveController
from mpctrano.scenarios import Scenario, run_scenario
from mpctrano.simulation import ClosedLoopResult, Plant
from mpctrano.synthetic import ExcitationSettings, SyntheticData, generate_monitoring_data, perturb


@dataclass
class Project:
    """A building under study: its Trano model, its monitoring data and the calibrated model."""

    model: RCModel
    """Model generated by Trano (initial parameters)."""
    forecaster: Forecaster
    calibrated: RCModel | None = None
    calibration: CalibrationResult | None = None
    data: MonitoringData | None = None
    validation: MonitoringData | None = None
    runs: dict[str, ClosedLoopResult] = field(default_factory=dict)

    # ----------------------------------------------------------------- constructors
    @classmethod
    def from_model(
        cls, model: RCModel, occupancy: OccupancySchedule | dict[str, OccupancySchedule] | None = None
    ) -> Project:
        return cls(model=model, forecaster=WeatherForecaster.from_model(model, occupancy=occupancy))

    @classmethod
    def from_yaml(cls, path: Path | str, model_type: RCModelType = RCModelType.r3c2, **kwargs: object) -> Project:
        """Generate the model with Trano from the building description."""
        return cls.from_model(RCModel.from_yaml(path, model_type=model_type), **kwargs)  # type: ignore[arg-type]

    @classmethod
    def from_files(cls, modelica: Path | str, interface: Path | str | None = None, **kwargs: object) -> Project:
        """Use the files written by ``trano create-model house.yaml mpc``."""
        return cls.from_model(RCModel.from_files(modelica, interface), **kwargs)  # type: ignore[arg-type]

    # ----------------------------------------------------------------- models
    @property
    def control_model(self) -> RCModel:
        """The calibrated model when available, the Trano model otherwise."""
        return self.calibrated or self.model

    def true_building(self, relative_std: float = 0.3, seed: int = 0) -> RCModel:
        """A perturbed copy of the Trano model playing the real building in studies."""
        return perturb(self.model, relative_std=relative_std, seed=seed)

    # ----------------------------------------------------------------- data
    def synthetic_data(
        self,
        days: float = 14,
        start: str | pd.Timestamp = "2023-01-02",
        time_step: float = 3600.0,
        building: RCModel | None = None,
        excitation: ExcitationSettings | None = None,
        measurement_std: float = 0.05,
    ) -> SyntheticData:
        """Monitoring data recorded on the true building (``building`` defaults to :meth:`true_building`)."""
        building = building or self.true_building()
        forecaster = WeatherForecaster.from_model(building, weather=self.model.weather_path)
        return generate_monitoring_data(
            building, forecaster, start, days, time_step, excitation=excitation, measurement_std=measurement_std
        )

    def load_data(self, data: MonitoringData, validation_fraction: float | None = 0.25) -> MonitoringData:
        """Register the monitoring data, fill the missing disturbances and split a validation period."""
        complete = data.fill_disturbances(self.model, self.forecaster)
        if validation_fraction:
            self.data, self.validation = complete.split(fraction=1 - validation_fraction)
        else:
            self.data, self.validation = complete, None
        return complete

    # ----------------------------------------------------------------- calibration
    def calibrate(
        self,
        data: MonitoringData | None = None,
        settings: CalibrationSettings | None = None,
        validation_fraction: float | None = 0.25,
    ) -> CalibrationResult:
        if data is not None:
            self.load_data(data, validation_fraction)
        if self.data is None:
            raise ValueError("Load monitoring data first.")
        calibrator = Calibrator(self.model, settings or CalibrationSettings())
        self.calibrated, self.calibration = calibrator.fit(self.data, self.validation)
        return self.calibration

    # ----------------------------------------------------------------- control
    def controller(self, scenario: Scenario) -> ModelPredictiveController:
        return ModelPredictiveController(self.control_model, scenario.settings, scenario.comfort, scenario.tariff)

    def run(
        self,
        scenario: Scenario,
        plant: Plant | RCModel | None = None,
        forecast_noise: ForecastNoise | None = None,
    ) -> ClosedLoopResult:
        """Closed loop of a scenario with the control model; ``plant`` defaults to the true building."""
        noise = forecast_noise or scenario.forecast_noise
        forecaster = WeatherForecaster.from_model(self.control_model, weather=self.model.weather_path, noise=noise)
        result = run_scenario(self.control_model, scenario, plant=plant, forecaster=forecaster)
        self.runs[scenario.name] = result
        return result

    # ----------------------------------------------------------------- persistence
    def save(self, directory: Path | str, stem: str | None = None) -> dict[str, Path]:
        """Write the model files (Trano and calibrated), the data and the runs."""
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        stem = stem or self.model.interface.package
        written: dict[str, Path] = {}
        written["modelica"], written["interface"] = self.model.write(directory, stem)
        if self.calibrated is not None:
            written["calibrated_interface"] = self.calibrated.portable_interface().write(
                directory / f"{stem}.calibrated.mpc.json"
            )
        if self.calibration is not None:
            path = directory / f"{stem}.calibration.json"
            path.write_text(self.calibration.model_dump_json(indent=2))
            written["calibration"] = path
        if self.data is not None:
            written["data"] = self.data.to_csv(directory / f"{stem}.training.csv")
        for name, run in self.runs.items():
            written[f"run_{name}"] = directory / f"{stem}.{name}.csv"
            run.frame.to_csv(written[f"run_{name}"])
        return written

    def load_calibrated(self, interface: Path | str) -> RCModel:
        """Use the parameters of a calibrated interface written by :meth:`save`."""
        from trano.mpc import MPCModelInterface

        calibrated = MPCModelInterface.read(interface)
        values = np.array(calibrated.parameter_values, dtype=float)
        self.calibrated = self.model.with_parameters(values)
        return self.calibrated
