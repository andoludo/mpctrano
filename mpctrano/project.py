"""High-level facade: from a Trano building to a calibrated model, MPC runs and their rule-based reference."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd

from mpctrano.calibration import CalibrationResult, CalibrationSettings, Calibrator
from mpctrano.data import MonitoringData
from mpctrano.forecast import ForecastNoise, OccupancySchedule, WeatherFile, WeatherForecaster
from mpctrano.model import CLOSED_LOOP_LIBRARY, FastModel
from mpctrano.mpc import ModelPredictiveController
from mpctrano.scenarios import Scenario, run_scenario, run_scenario_rule_based
from mpctrano.simulation import ClosedLoopResult, Plant
from mpctrano.synthetic import SyntheticData, generate_monitoring_data, perturb, random_factors


@dataclass
class Project:
    """A building under study: its Trano models, its monitoring data and the calibrated model.

    ``model`` is the ``FastModelMPC`` model the controller uses; the closed-loop ``FastModel`` of the same YAML
    (:meth:`closed_loop`) runs the controllers of the YAML, the reference of the MPC.
    """

    model: FastModel
    """Model generated by Trano (initial parameters)."""
    forecaster: WeatherForecaster
    source: Path | None = None
    """The YAML description, to generate the closed-loop model."""
    calibrated: FastModel | None = None
    calibration: CalibrationResult | None = None
    data: MonitoringData | None = None
    validation: MonitoringData | None = None
    runs: dict[str, ClosedLoopResult] = field(default_factory=dict)
    _closed_loop: FastModel | None = field(default=None, init=False, repr=False)

    # ----------------------------------------------------------------- constructors
    @classmethod
    def from_model(
        cls,
        model: FastModel,
        weather: WeatherFile | Path | str | None = None,
        occupancy: OccupancySchedule | dict[str, OccupancySchedule] | None = None,
        source: Path | str | None = None,
    ) -> Project:
        forecaster = WeatherForecaster.from_model(model, weather=weather, occupancy=occupancy)
        return cls(model=model, forecaster=forecaster, source=Path(source) if source else None)

    @classmethod
    def from_yaml(
        cls,
        path: Path | str,
        weather: WeatherFile | Path | str | None = None,
        occupancy: OccupancySchedule | dict[str, OccupancySchedule] | None = None,
    ) -> Project:
        """Generate the ``FastModelMPC`` model with Trano from the building description."""
        return cls.from_model(FastModel.from_yaml(path), weather=weather, occupancy=occupancy, source=path)

    @classmethod
    def from_file(
        cls,
        modelica: Path | str,
        weather: WeatherFile | Path | str | None = None,
        occupancy: OccupancySchedule | dict[str, OccupancySchedule] | None = None,
    ) -> Project:
        """Use the package written by ``trano create-model house.yaml FastModelMPC`` (without the YAML, the
        occupancy schedules must be given and the rule-based reference is not available)."""
        return cls.from_model(FastModel.from_file(modelica), weather=weather, occupancy=occupancy)

    # ----------------------------------------------------------------- models
    @property
    def control_model(self) -> FastModel:
        """The calibrated model when available, the Trano model otherwise."""
        return self.calibrated or self.model

    def closed_loop(self) -> FastModel:
        """The closed-loop ``FastModel`` of the YAML: the building with the controllers it describes."""
        if self._closed_loop is None:
            if self.source is None:
                raise ValueError("The closed-loop model needs the YAML description of the building.")
            self._closed_loop = FastModel.from_yaml(self.source, library=CLOSED_LOOP_LIBRARY)
        return self._closed_loop

    def true_building(self, relative_std: float = 0.3, seed: int = 0) -> FastModel:
        """A copy of the Trano model with its parameter groups at random values, playing the real building."""
        return perturb(self.model, relative_std=relative_std, seed=seed)

    def with_groups(self, model: FastModel, factors: dict[str, float]) -> FastModel:
        """``model`` (e.g. the closed-loop model) with the parameter groups at ``factors``."""
        calibrator = Calibrator(model)
        return calibrator.calibrated({group.name: factors[group.name] for group in calibrator.groups})

    def true_closed_loop(self, relative_std: float = 0.3, seed: int = 0) -> FastModel:
        """The closed-loop model of the same true building as :meth:`true_building`."""
        return self.with_groups(self.closed_loop(), random_factors(relative_std, seed))

    # ----------------------------------------------------------------- data
    def synthetic_data(
        self,
        days: float = 7,
        start: str | pd.Timestamp = "2023-01-02",
        time_step: float = 3600.0,
        building: FastModel | None = None,
        measurement_std: float = 0.05,
        seed: int | None = 0,
    ) -> SyntheticData:
        """Monitoring data recorded on the true building (``building`` defaults to :meth:`true_building`)."""
        building = building or self.true_building()
        forecaster = WeatherForecaster.from_model(building, weather=self.forecaster.weather)
        return generate_monitoring_data(
            building, start, days, time_step, forecaster=forecaster, measurement_std=measurement_std, seed=seed
        )

    def load_data(self, data: MonitoringData, validation_fraction: float | None = 0.25) -> MonitoringData:
        """Register the monitoring data, fill the missing disturbances and split a validation period."""
        complete = data.fill_disturbances(self.model, self.forecaster)
        if validation_fraction:
            self.data, self.validation = complete.split(fraction=1 - validation_fraction)
        else:
            self.data, self.validation = complete, None
        return complete

    # ----------------------------------------------------------------- calibration
    def calibrate(
        self,
        data: MonitoringData | None = None,
        settings: CalibrationSettings | None = None,
        validation_fraction: float | None = 0.25,
    ) -> CalibrationResult:
        if data is not None:
            self.load_data(data, validation_fraction)
        if self.data is None:
            raise ValueError("Load monitoring data first.")
        calibrator = Calibrator(self.model, settings or CalibrationSettings())
        self.calibrated, self.calibration = calibrator.fit(self.data, self.validation)
        return self.calibration

    # ----------------------------------------------------------------- control
    def controller(self, scenario: Scenario) -> ModelPredictiveController:
        return ModelPredictiveController(self.control_model, scenario.settings, scenario.comfort, scenario.tariff)

    def run(
        self,
        scenario: Scenario,
        plant: Plant | FastModel | None = None,
        forecast_noise: ForecastNoise | None = None,
    ) -> ClosedLoopResult:
        """Closed loop of a scenario with the control model; ``plant`` defaults to the control model itself."""
        noise = forecast_noise or scenario.forecast_noise
        forecaster = self.forecaster.with_noise(noise)
        if forecaster.model is not self.control_model:
            forecaster = WeatherForecaster(
                model=self.control_model, weather=forecaster.weather, occupancy=forecaster.occupancy, noise=noise
            )
        result = run_scenario(self.control_model, scenario, plant=plant, forecaster=forecaster)
        self.runs[scenario.name] = result
        return result

    def run_rule_based(self, scenario: Scenario, building: FastModel | None = None) -> ClosedLoopResult:
        """The controllers of the YAML over the scenario: on ``building`` (a closed-loop model, e.g.
        :meth:`true_closed_loop`), by default on the closed-loop model with the calibrated groups if any."""
        if building is None:
            building = self.closed_loop()
            if self.calibration is not None:
                building = self.with_groups(building, self.calibration.factors)
        forecaster = WeatherForecaster.from_model(building, weather=self.forecaster.weather)
        result = run_scenario_rule_based(building, scenario, forecaster)
        self.runs[result.name] = result
        return result

    # ----------------------------------------------------------------- persistence
    def save(self, directory: Path | str, stem: str | None = None) -> dict[str, Path]:
        """Write the model, the calibration, the data and the runs."""
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        stem = stem or self.model.name.split(".")[0]
        written: dict[str, Path] = {"modelica": self.model.write(directory, stem)}
        if self.calibration is not None:
            path = directory / f"{stem}.calibration.json"
            path.write_text(self.calibration.model_dump_json(indent=2))
            written["calibration"] = path
        if self.data is not None:
            written["data"] = self.data.to_csv(directory / f"{stem}.training.csv")
        for name, run in self.runs.items():
            written[f"run_{name}"] = directory / f"{stem}.{name.replace(' ', '_')}.csv"
            run.frame.to_csv(written[f"run_{name}"])
        return written

    def load_calibrated(self, path: Path | str) -> FastModel:
        """Use the calibration written by :meth:`save` (``<stem>.calibration.json``)."""
        self.calibration = CalibrationResult.model_validate(json.loads(Path(path).read_text()))
        self.calibrated = self.model.with_parameters(self.calibration.parameters)
        return self.calibrated
